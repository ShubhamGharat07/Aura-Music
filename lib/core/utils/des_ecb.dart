// Minimal DES in ECB mode (FIPS 46-3), used to decode JioSaavn CDN links.
//
// JioSaavn returns base64-encoded, DES-ECB (PKCS#5 padding) encrypted media
// URLs; decrypting them client-side is the only way to obtain a playable
// stream. The implementation is self-contained (no crypto dependency) and is
// verified against the canonical FIPS test vector in unit tests.
//
// Blocks run on 64-bit integers (each permutation is a bit move on an int),
// so decoding a whole screenful of URLs allocates nothing per bit. The
// 16-round key schedule is cached per key.

/// DES-ECB block codec with PKCS#5 unpadding helpers.
abstract final class DesEcb {
  /// Decrypts a whole buffer, one 8-byte block at a time.
  static Uint8List decryptBytes(Uint8List input, Uint8List key) =>
      _crypt(input, key, decrypt: true);

  /// Encrypts a whole buffer (exposed for round-trip tests).
  static Uint8List encryptBytes(Uint8List input, Uint8List key) =>
      _crypt(input, key, decrypt: false);

  /// Base64-decodes [cipherBase64], decrypts it with the UTF-8 [keyUtf8],
  /// strips PKCS#5 padding and returns the trimmed UTF-8 text (empty on
  /// malformed input).
  static String decryptBase64ToString(String cipherBase64, String keyUtf8) {
    final trimmed = cipherBase64.trim();
    if (trimmed.isEmpty) return '';
    final Uint8List decoded;
    try {
      decoded = base64.decode(trimmed);
    } on FormatException {
      return '';
    }
    if (decoded.isEmpty) return '';
    final key = Uint8List.fromList(utf8.encode(keyUtf8));
    return _stripPadding(_crypt(decoded, key, decrypt: true));
  }

  static const int _blockSize = 8;
  static final Map<String, List<int>> _scheduleCache = <String, List<int>>{};

  static Uint8List _crypt(
    Uint8List input,
    Uint8List key, {
    required bool decrypt,
  }) {
    if (input.length < _blockSize) return Uint8List(0);
    final subkeys = _subkeysFor(key);
    final out = Uint8List(input.length - input.length % _blockSize);
    for (
      var offset = 0;
      offset + _blockSize <= input.length;
      offset += _blockSize
    ) {
      final block = _cryptBlock(_bytesToInt(input, offset), subkeys, decrypt);
      for (var i = 0; i < _blockSize; i++) {
        out[offset + i] = (block >> (56 - i * 8)) & 0xFF;
      }
    }
    return out;
  }

  static List<int> _subkeysFor(Uint8List key) {
    final cacheKey = String.fromCharCodes(key);
    return _scheduleCache[cacheKey] ??= _keySchedule(key);
  }

  static List<int> _keySchedule(Uint8List key) {
    final permuted = _permute(_bytesToInt(key), 64, _pc1);
    var c = permuted >> 28;
    var d = permuted & 0xFFFFFFF;
    final subkeys = List<int>.filled(16, 0);
    for (var round = 0; round < 16; round++) {
      final shift = _shifts[round];
      c = _rotateLeft28(c, shift);
      d = _rotateLeft28(d, shift);
      subkeys[round] = _permute((c << 28) | d, 56, _pc2);
    }
    return subkeys;
  }

  static int _cryptBlock(int block, List<int> subkeys, bool decrypt) {
    final permuted = _permute(block, 64, _ip);
    var left = (permuted >> 32) & 0xFFFFFFFF;
    var right = permuted & 0xFFFFFFFF;
    for (var round = 0; round < 16; round++) {
      final mixed = _feistel(right, subkeys[decrypt ? 15 - round : round]);
      final next = (left ^ mixed) & 0xFFFFFFFF;
      left = right;
      right = next;
    }
    return _permute((right << 32) | left, 64, _fp);
  }

  static int _feistel(int right, int subkey) {
    final x = _permute(right, 32, _e) ^ subkey;
    var sOut = 0;
    for (var box = 0; box < 8; box++) {
      final group = (x >> (42 - box * 6)) & 0x3F;
      final row = ((group >> 4) & 0x2) | (group & 0x1);
      final col = (group >> 1) & 0xF;
      sOut = (sOut << 4) | _sBoxes[box][row * 16 + col];
    }
    return _permute(sOut, 32, _p);
  }

  static int _permute(int input, int inputBits, List<int> table) {
    var out = 0;
    for (var i = 0; i < table.length; i++) {
      out = (out << 1) | ((input >> (inputBits - table[i])) & 1);
    }
    return out;
  }

  static int _rotateLeft28(int value, int count) =>
      ((value << count) | (value >> (28 - count))) & 0xFFFFFFF;

  static int _bytesToInt(Uint8List bytes, [int offset = 0]) {
    var value = 0;
    for (var i = 0; i < 8; i++) {
      value = (value << 8) | bytes[offset + i];
    }
    return value;
  }

  static String _stripPadding(Uint8List bytes) {
    var end = bytes.length;
    if (end > 0) {
      final pad = bytes[end - 1];
      if (pad >= 1 && pad <= 8 && pad <= end) {
        end -= pad;
      } else {
        while (end > 0 && bytes[end - 1] < 0x20) {
          end--;
        }
      }
    }
    return utf8.decode(bytes.sublist(0, end), allowMalformed: true).trim();
  }

